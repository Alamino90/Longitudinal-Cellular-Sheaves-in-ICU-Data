import numpy as np
import pandas as pd

# ==============================================================================
# 0. SETTINGS
# ==============================================================================
ID, TARGET, TIME = "Patient_ID", "SepsisLabel", "ICULOS"
VITALS = ["HR", "O2Sat", "MAP", "Resp", "SBP", "DBP", "Temp", "EtCO2"]
VITALS_FFILL_LIMIT = 12        # hours; labs are forward-filled without a limit
MISSING_FLAG_THRESHOLD = 0.80  # row-level missing fraction that triggers indicator columns
REF_RATIO, SEED = 0.5, 42

# ==============================================================================
# 1. DROP FEATURES
# ==============================================================================
cols_to_drop = [
    "Unnamed: 0", "Hour",
    "Bilirubin_direct", "TroponinI", "Fibrinogen",
    "Unit1", "Unit2",
]
df_cleaned = df.drop(columns=[c for c in cols_to_drop if c in df.columns])

# ==============================================================================
# 2. COLUMN ROLES, CHRONOLOGY, MISSINGNESS INDICATORS
# ==============================================================================
meta_cols = [ID, TARGET, TIME, "Age", "Gender", "HospAdmTime"]
clinical_features = [c for c in df_cleaned.columns if c not in meta_cols]
vitals = [c for c in VITALS if c in clinical_features]
labs = [c for c in clinical_features if c not in vitals]

df_cleaned = df_cleaned.sort_values([ID, TIME]).reset_index(drop=True)

# Forward-fill limits (VITALS_FFILL_LIMIT, and consecutive_pairs' diff(t)==1
# check in the v2 pipeline) both assume rows are exactly 1 hour apart. This is
# now a hard requirement, not a diagnostic: if it's violated, ffill(limit=12)
# silently means something other than "12 hours," so we stop here instead of
# proceeding on a false assumption.
gaps = df_cleaned.groupby(ID)[TIME].diff().dropna()
n_bad_gaps = int((gaps != 1).sum())
print(f"CHECK 1 - rows whose time step is not 1 hour: {n_bad_gaps:,}  (expect 0)")
if n_bad_gaps > 0:
    raise ValueError(
        f"Found {n_bad_gaps:,} non-1-hour gaps in patient timelines. "
        "ffill(limit=VITALS_FFILL_LIMIT) cannot be interpreted as an "
        "hour-based limit unless every row is exactly 1 hour apart. "
        "Fix the input data (e.g. reindex to a continuous hourly grid per "
        "patient) before proceeding."
    )

observed = df_cleaned[clinical_features].notna()
for col in clinical_features:
    df_cleaned[f"{col}_is_missing"] = (~observed[col]).astype("int8")

flag_cols = [c for c in clinical_features
             if df_cleaned[c].isnull().mean() > MISSING_FLAG_THRESHOLD]
for col in flag_cols:
    last_seen = (df_cleaned[TIME].where(observed[col])
                 .groupby(df_cleaned[ID]).ffill().fillna(0))   # never measured yet -> counts from admission
    df_cleaned[f"{col}_hours_since"] = df_cleaned[TIME] - last_seen

# ==============================================================================
# 3. PATIENT-LEVEL COHORT SPLIT (BEFORE ANY IMPUTATION)
# ==============================================================================
patient_max = df_cleaned.groupby(ID)[TARGET].max()
septic_ids = patient_max.index[patient_max == 1].to_numpy()
all_normal_ids = patient_max.index[patient_max == 0].to_numpy()

np.random.seed(SEED)   # same generator as before, so the split is identical to your earlier runs
ref_normal_ids = np.random.choice(all_normal_ids, size=int(len(all_normal_ids) * REF_RATIO), replace=False)
analysis_normal_ids = np.setdiff1d(all_normal_ids, ref_normal_ids)

df_cleaned["Cohort_Group"] = "Analysis_Normal"
df_cleaned.loc[df_cleaned[ID].isin(ref_normal_ids), "Cohort_Group"] = "Reference_Normal"
df_cleaned.loc[df_cleaned[ID].isin(septic_ids), "Cohort_Group"] = "Septic"

# ==============================================================================
# 4. FALLBACK VALUES FROM REFERENCE NORMALS (RAW OBSERVED VALUES, BEFORE FFILL)
# ==============================================================================
fill_cols = clinical_features + ["HospAdmTime"]
ref_rows = df_cleaned[df_cleaned["Cohort_Group"] == "Reference_Normal"]
# median per patient first, then median across patients: long stays do not dominate
ref_normal_medians = ref_rows.groupby(ID)[fill_cols].median().median()

# ==============================================================================
# 5. WITHIN-PATIENT FORWARD FILL (REAL-TIME SAFE: NO BACKWARD FILL)
# ==============================================================================
df_cleaned[vitals] = df_cleaned.groupby(ID)[vitals].ffill(limit=VITALS_FFILL_LIMIT)
df_cleaned[labs]   = df_cleaned.groupby(ID)[labs].ffill()

# ==============================================================================
# 6. FALLBACK FILL (leading gaps, vitals gaps > limit, never-measured variables)
# ==============================================================================
df_cleaned[fill_cols] = df_cleaned[fill_cols].fillna(ref_normal_medians)

print("=" * 80)
print(f"• Reference Normal Patients (Baseline / A_hat training): {len(ref_normal_ids):,}")
print(f"• Analysis Normal Patients (Evaluation):                {len(analysis_normal_ids):,}")
print(f"• Septic Patients (Evaluation):                         {len(septic_ids):,}")
print(f"CHECK 2 - remaining NaNs in the whole dataframe:        {int(df_cleaned.isnull().sum().sum())}  (expect 0)")

