# ==============================================================================
# HELPERS
# ==============================================================================
def rank_biserial(x1, x2):
    """r_rb = 2*U1/(n1*n2) - 1 (U1 from midranks; independent of SciPy version).
    Positive => x1 (Sepsis Positive) tends to be larger than x2."""
    n1, n2 = len(x1), len(x2)
    ranks = rankdata(np.concatenate([x1, x2]))
    u1 = ranks[:n1].sum() - n1 * (n1 + 1) / 2
    return 2.0 * u1 / (n1 * n2) - 1.0


def bootstrap_ci(x1, x2, B=B_BOOT, seed=SEED):
    """Stratified PATIENT bootstrap CI for r_rb (resamples patients, not edges)."""
    rng = np.random.default_rng(seed)
    r = np.array([rank_biserial(rng.choice(x1, len(x1)), rng.choice(x2, len(x2)))
                  for _ in range(B)])
    return np.percentile(r, [2.5, 97.5])


def benjamini_hochberg(p):
    p = np.asarray(p, dtype=float)
    n = len(p)
    order = np.argsort(p)
    q = np.empty(n)
    q[order] = np.minimum.accumulate((p[order] * n / np.arange(1, n + 1))[::-1])[::-1]
    return np.minimum(q, 1.0)


