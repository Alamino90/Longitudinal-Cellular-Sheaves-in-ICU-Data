import numpy as np
import pandas as pd
import scipy.sparse as sp
from sklearn.model_selection import GroupKFold

# ==============================================================================
# CONFIG
# ==============================================================================
ALPHAS = [0.1, 1.0, 10.0, 100.0, 1000.0, 5000.0, 10000.0, 50000.0, 100000.0]
CV_FOLDS = 5
MIN_PAIRS = 500
MIN_OBS_FEATURES = 3
MIN_HISTORY = 12
WINDOW = (-48, 0)
SEED = 42

# ==============================================================================
# STAGE 1: COHORT PARTITION VERIFICATION
# ==============================================================================
required = {"Cohort_Group", "Patient_ID", "ICULOS", "SepsisLabel"}
if required - set(df_cleaned.columns):
    raise ValueError(f"Missing columns: {required - set(df_cleaned.columns)}")

df_ref = df_cleaned[df_cleaned["Cohort_Group"] == "Reference_Normal"].copy()
df_analysis = df_cleaned[
    df_cleaned["Cohort_Group"].isin(["Analysis_Normal", "Septic"])
].copy()

ref_ids = set(df_ref["Patient_ID"].unique())
analysis_normal_ids = df_cleaned.loc[
    df_cleaned["Cohort_Group"] == "Analysis_Normal", "Patient_ID"
].unique().tolist()
sepsis_ids = set(
    df_cleaned.loc[df_cleaned["Cohort_Group"] == "Septic", "Patient_ID"].unique()
)
normal_set = set(analysis_normal_ids)

assert ref_ids.isdisjoint(normal_set), "Leakage: Reference overlaps Analysis Normal."
assert ref_ids.isdisjoint(sepsis_ids), "Leakage: Reference overlaps Septic."
assert normal_set.isdisjoint(sepsis_ids), "Leakage: Analysis Normal overlaps Septic."

print("=" * 80)
print("STAGE 1: COHORT PARTITION VERIFIED")
print("=" * 80)
print(f"Reference Normal: {len(ref_ids):,} | Analysis Normal: {len(normal_set):,} "
      f"| Septic: {len(sepsis_ids):,}")

# ==============================================================================
# STAGE 2: FEATURES & OBSERVATION MASKS
# ==============================================================================
meta_cols = ["Patient_ID", "SepsisLabel", "ICULOS", "Age", "Gender",
             "HospAdmTime", "Cohort_Group"]

feature_cols = [
    c for c in df_cleaned.columns
    if c not in meta_cols and not c.endswith(("_is_missing", "_hours_since"))
]
d = len(feature_cols)
if d == 0:
    raise ValueError("No physiological features available.")

no_flag = [c for c in feature_cols if f"{c}_is_missing" not in df_cleaned.columns]
if no_flag:
    print(f"WARNING: no *_is_missing flag for {no_flag}. They are treated as "
          f"observed wherever finite; if they were imputed, this is biased.")


def observation_matrix(df):
    """Boolean (n x d) matrix: True where the value was ORIGINALLY observed."""
    cols = []
    for c in feature_cols:
        flag = f"{c}_is_missing"
        m = (df[flag].to_numpy() == 0) if flag in df.columns else np.ones(len(df), bool)
        cols.append(m & np.isfinite(df[c].to_numpy(dtype=float)))
    return np.column_stack(cols)


# ==============================================================================
# STAGE 3: OBSERVED-ONLY STANDARDIZATION (Reference Normal only)
# ==============================================================================
X_ref = df_ref[feature_cols].to_numpy(dtype=float)
M_ref = observation_matrix(df_ref)

if (M_ref.sum(axis=0) < 2).any():
    bad = [feature_cols[j] for j in np.flatnonzero(M_ref.sum(axis=0) < 2)]
    raise ValueError(f"Too few observed Reference values for: {bad}")

mu = np.array([X_ref[M_ref[:, j], j].mean() for j in range(d)])
sd = np.array([X_ref[M_ref[:, j], j].std(ddof=1) for j in range(d)])
sd[~np.isfinite(sd) | (sd == 0)] = 1.0


def prepare(df):
    """Sort by patient/time; return scaled states, observation mask, ids, times."""
    df = df.reset_index(drop=True)
    order = df.sort_values(["Patient_ID", "ICULOS"]).index.to_numpy()
    Z = (df[feature_cols].to_numpy(dtype=float)[order] - mu) / sd
    Z = np.nan_to_num(Z, nan=0.0)               # unobserved -> reference mean
    M = observation_matrix(df)[order]
    return Z, M, df["Patient_ID"].to_numpy()[order], df["ICULOS"].to_numpy()[order]


# ==============================================================================
# STAGE 4: STRICT 1-HOUR TRANSITIONS (with observation masks)
# ==============================================================================
def consecutive_pairs(Z, M, pid, t):
    same = pid[1:] == pid[:-1]
    if (same & (t[1:] == t[:-1])).any():
        raise ValueError("Duplicate ICULOS within a patient.")
    v = same & (np.diff(t) == 1)
    return Z[:-1][v], Z[1:][v], M[:-1][v], M[1:][v], pid[1:][v], t[1:][v]


Z_t, Z_t1, M_t, M_t1, pair_pid, _ = consecutive_pairs(*prepare(df_ref))
if Z_t.shape[0] == 0:
    raise ValueError("No 1-hour transitions in Reference Normal.")

# A feature is "estimable" only if enough transitions were truly observed at BOTH
# t and t+1 (otherwise the transition is just carried-forward imputation).
n_pairs = (M_t & M_t1).sum(axis=0)
est = n_pairs >= MIN_PAIRS
if not est.any():
    raise ValueError("No feature has enough observed->observed transitions.")
dropped = [feature_cols[j] for j in np.flatnonzero(~est)]

# ==============================================================================
# STAGE 5: PATIENT-BALANCED MASKED RIDGE, alpha CHOSEN BY GROUPED CV
# ==============================================================================
def patient_weights(pids):
    _, inv, counts = np.unique(pids, return_inverse=True, return_counts=True)
    w = 1.0 / counts[inv]
    return w * len(w) / w.sum()


def gram_stats(Zt, Zt1, Mt, Mt1, w):
    """Per-target-feature weighted normal equations, using only rows where the
    target was genuinely observed at t and t+1."""
    G = np.zeros((d, d, d))
    B = np.zeros((d, d))
    for j in range(d):
        r = Mt[:, j] & Mt1[:, j]
        if not r.any():
            continue
        X, wr = Zt[r], w[r]
        G[j] = X.T @ (X * wr[:, None])
        B[j] = X.T @ (wr * Zt1[r, j])
    return G, B


def solve_A(G, B, alpha, est):
    A = np.zeros((d, d))
    I = np.eye(d)
    for j in np.flatnonzero(est):
        A[j] = np.linalg.solve(G[j] + alpha * I, B[j])
    return A


def masked_residuals(Zt, Zt1, Mt, Mt1, A, est):
    R = Zt1 - Zt @ A.T
    V = Mt & Mt1 & est[None, :]
    return np.where(V, R, 0.0), V


w = patient_weights(pair_pid)
G_tot, B_tot = gram_stats(Z_t, Z_t1, M_t, M_t1, w)

sse = dict.fromkeys(ALPHAS, 0.0)
sse_persist, den = 0.0, 0.0
I_d = np.eye(d)
for tr, va in GroupKFold(n_splits=CV_FOLDS).split(Z_t, groups=pair_pid):
    G_va, B_va = gram_stats(Z_t[va], Z_t1[va], M_t[va], M_t1[va], w[va])
    G_tr, B_tr = G_tot - G_va, B_tot - B_va
    wv = w[va][:, None]
    R0, V0 = masked_residuals(Z_t[va], Z_t1[va], M_t[va], M_t1[va], I_d, est)
    sse_persist += (wv * R0 ** 2).sum()
    den += (wv * V0).sum()
    for a in ALPHAS:
        R, _ = masked_residuals(Z_t[va], Z_t1[va], M_t[va], M_t1[va],
                                solve_A(G_tr, B_tr, a, est), est)
        sse[a] += (wv * R ** 2).sum()

cv_mse = {a: sse[a] / den for a in ALPHAS}
best_alpha = min(cv_mse, key=cv_mse.get)
if best_alpha in (ALPHAS[0], ALPHAS[-1]):
    print(f"WARNING: best_alpha ({best_alpha:g}) is at the edge of ALPHAS "
          f"({ALPHAS[0]:g}..{ALPHAS[-1]:g}). The grid minimum may not be the "
          f"true minimum — widen ALPHAS and re-run before trusting this value.")
A_hat = solve_A(G_tot, B_tot, best_alpha, est)

# Per-feature residual scale (so no single noisy variable dominates the norm)
R_ref, V_ref = masked_residuals(Z_t, Z_t1, M_t, M_t1, A_hat, est)
res_sd = np.sqrt((w[:, None] * R_ref ** 2).sum(0)
                 / np.maximum((w[:, None] * V_ref).sum(0), 1e-12))
res_sd[~est | (res_sd == 0)] = 1.0

spectral_radius = np.max(np.abs(np.linalg.eigvals(A_hat)))

print("\n" + "=" * 80)
print("STAGE 2-5: A_hat ESTIMATION COMPLETE")
print("=" * 80)
print(f"Variables (d):                      {d}  (scored: {int(est.sum())})")
if dropped:
    print(f"Not scored (few observed pairs):    {dropped}")
print(f"Reference 1-hour transitions:       {Z_t.shape[0]:,}")
print(f"CV MSE by alpha:                    "
      + ", ".join(f"{a:g}: {m:.4f}" for a, m in cv_mse.items()))
print(f"Best alpha:                         {best_alpha:g}")
print(f"CV MSE persistence (z_t+1 = z_t):   {sse_persist / den:.4f}")
print(f"Spectral radius of A_hat:           {spectral_radius:.4f}")
if spectral_radius >= 1:
    print("WARNING: spectral radius >= 1 (unstable dynamics).")
if cv_mse[best_alpha] >= sse_persist / den:
    print("WARNING: A_hat does not beat the persistence baseline; the sheaf "
          "residual adds nothing over plain differencing.")

# ==============================================================================
# STAGE 6: SPARSE CELLULAR-SHEAF COBOUNDARY OPERATOR
# ==============================================================================
def construct_sheaf_coboundary(A, N, d):
    """delta^0 = S1 (x) I_d - S0 (x) A, shape d(N-1) x dN."""
    if N < 2:
        raise ValueError("N must be >= 2.")
    if A.shape != (d, d):
        raise ValueError(f"A shape {A.shape} incompatible with d={d}.")
    S0 = sp.eye(N - 1, N, k=0, format="csr")
    S1 = sp.eye(N - 1, N, k=1, format="csr")
    return (sp.kron(S1, sp.eye(d, format="csr"), format="csr")
            - sp.kron(S0, sp.csr_matrix(A), format="csr"))


# Numerical verification: delta^0 @ vec(Z) must equal the edge residuals.
N_example = 24
Z_test = np.random.default_rng(0).standard_normal((N_example, d))
delta_0 = construct_sheaf_coboundary(A_hat, N_example, d)
assert delta_0.shape == (d * (N_example - 1), d * N_example)
assert np.allclose(delta_0 @ Z_test.ravel(),
                   (Z_test[1:] - Z_test[:-1] @ A_hat.T).ravel()), \
    "Coboundary does not reproduce edge residuals."

# ==============================================================================
# STAGE 7-8: ANALYSIS-COHORT MASKED, SCALED RESIDUALS
# ==============================================================================
Z_a, Z_a1, M_a, M_a1, pid_a, t_a = consecutive_pairs(*prepare(df_analysis))
if Z_a.shape[0] == 0:
    raise ValueError("No 1-hour transitions in the Analysis cohort.")

R_a, V_a = masked_residuals(Z_a, Z_a1, M_a, M_a1, A_hat, est)
R_a = R_a / res_sd
n_obs = V_a.sum(axis=1)
# sheaf_residual_norm (RMS) and sheaf energy E
# are the same underlying quantity at different aggregation levels:
#   E        = mean squared standardized residual per observed transition
#   sqrt(E)  = RMS sheaf residual norm
norms = np.sqrt((R_a ** 2).sum(axis=1) / np.maximum(n_obs, 1))

edge_df = pd.DataFrame({
    "Patient_ID": pid_a,
    "ICULOS": t_a,
    "sheaf_residual_norm": norms,
    "n_obs_features": n_obs,     # sampling-intensity covariate: check/adjust for it
})
edge_df = edge_df[edge_df["n_obs_features"] >= MIN_OBS_FEATURES].copy()

# ==============================================================================
# STAGE 9: ONSET AND FEASIBILITY-CONSTRAINED PSEUDO-ONSET

first_t = df_analysis.groupby("Patient_ID")["ICULOS"].min()
last_t = df_analysis.groupby("Patient_ID")["ICULOS"].max()

onset_all = (
    df_analysis.loc[df_analysis["SepsisLabel"] == 1]
    .groupby("Patient_ID")["ICULOS"].min()
)
onset_all = onset_all[onset_all.index.isin(sepsis_ids)]

history = onset_all - first_t.reindex(onset_all.index)
onset_times = onset_all[history >= MIN_HISTORY]
n_septic_short = len(onset_all) - len(onset_times)

rng = np.random.default_rng(SEED)
valid_onsets = onset_times.to_numpy()
pseudo_onsets, unmatched_controls = {}, 0

for p in analysis_normal_ids:
    lo = first_t.get(p, np.nan) + MIN_HISTORY
    hi = last_t.get(p, np.nan)
    if not (np.isfinite(lo) and np.isfinite(hi)):
        unmatched_controls += 1
        continue
    eligible = valid_onsets[(valid_onsets >= lo) & (valid_onsets <= hi)]
    if len(eligible) == 0:
        unmatched_controls += 1
    else:
        pseudo_onsets[p] = rng.choice(eligible)

t_ref = pd.concat([onset_times.astype(float),
                   pd.Series(pseudo_onsets, dtype=float)])

edge_df["reference_time"] = edge_df["Patient_ID"].map(t_ref)
edge_df["rel_hour"] = edge_df["ICULOS"] - edge_df["reference_time"]

# ==============================================================================
# STAGE 10: ONSET-ALIGNED WINDOW
# ==============================================================================
edge_window = edge_df[edge_df["rel_hour"].between(*WINDOW)].copy()
edge_window["Cohort"] = np.where(
    edge_window["Patient_ID"].isin(onset_times.index),
    "Sepsis Positive", "Sepsis Negative"
)

# Patient-level summary: edges within a patient are correlated, so any test or
# model must be done on these (or with patient random effects), not on raw edges.
edge_window["rel_hour_bin"] = (edge_window["rel_hour"] // 6) * 6
patient_level = (
    edge_window
    .groupby(["Cohort", "Patient_ID", "rel_hour_bin"])
    .agg(resid=("sheaf_residual_norm", "mean"),
         n_obs=("n_obs_features", "mean"),
         n_edges=("sheaf_residual_norm", "size"))
    .reset_index()
)

# ==============================================================================
# STAGE 11: DIAGNOSTICS
# ==============================================================================
print("\n" + "=" * 80)
print("STAGE 6-10: ONSET-ALIGNED SHEAF RESIDUAL ANALYSIS COMPLETE")
print("=" * 80)
print(f"Edges in window:                     {len(edge_window):,}")
print(f"Septic with onset + history:         {len(onset_times):,} "
      f"(excluded for short history: {n_septic_short:,})")
print(f"Controls with pseudo-onset:          {len(pseudo_onsets):,} "
      f"(excluded: {unmatched_controls:,})")
for name in ["Sepsis Positive", "Sepsis Negative"]:
    sub = edge_window[edge_window["Cohort"] == name]
    print(f"{name:<17} edges: {len(sub):>9,} | patients: {sub['Patient_ID'].nunique():>6,} "
          f"| mean obs-features/edge: {sub['n_obs_features'].mean():.2f}")
print(f"delta^0 check passed | shape {delta_0.shape} | nnz {delta_0.nnz:,}")

